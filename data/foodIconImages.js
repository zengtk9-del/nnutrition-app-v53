// Real artwork for the food cards and list rows in LogFoodScreen.js, keyed
// by the exact `iconKey` each card builds (see each card's `iconKey` there,
// and `rowIconKeyOf` for the list rows).
//
// 1713 entries, wired in v0.0.50 from Damon's drawn set.
//
// ---------------------------------------------------------------------
// They are .jpg, not .png, as of v0.0.53
//
// The drawn set came out of the generator at full resolution: 1,749 PNGs
// totalling 2.58 GB, about 1.47 MB apiece, for pictures this app displays
// at 96pt in a list row and 192pt on a card. That is far past anything
// Snack will accept, and past what a phone should be asked to download.
//
// Resizing to 384px and re-encoding at JPEG quality 85 brought the whole
// set to roughly 55 MB -- about 1/47th the size -- with no visible loss on
// this art style. PNG alone (resize, no format change) only reached 279 MB,
// because these illustrations are soft gradients and PNG compresses those
// badly; that is the entire reason for the format change.
//
// The one thing JPEG cannot carry is transparency. The conversion flattened
// every image onto white (`-background white -flatten`), so each icon is now
// an opaque white square. `rowIconWrap` in LogFoodScreen.js was changed to a
// white background in the same round so no seam shows around the artwork.
// If icons are ever redrawn to sit on a coloured surface, that is the style
// to revisit.
//
// The quiz artwork (data/quizQuestions.js, 35 files) went through the same
// conversion and points at .jpg too.
//
// ---------------------------------------------------------------------
// Both this file and the quiz artwork point into assets/
//
// Snack's own importer drops files at the project root regardless of what is
// selected in the file tree, and it caps a folder import at 100 files, so
// neither route gets 1,749 icons filed correctly. Importing the project from
// GitHub does, which is why the paths below are `../assets/<name>.jpg`.
//
// ---------------------------------------------------------------------
// Filenames are NOT always `<iconKey>.jpg`
//
// They used to be, and mostly still are -- but this map exists precisely so
// they don't have to be. Two groups were drawn with a `_large` suffix that
// the icon key no longer carries:
//
//   milk_whole          -> milk_whole_large.jpg
//   chicken_whole_raw   -> chicken_whole_raw_large.jpg   (and 20 more eggs)
//
// That happened because egg SIZE and milk LACTOSE-FREE used to be part of
// the icon key. They were removed in v0.0.50: a small egg and a jumbo egg
// are the same drawing at 96px, and lactose-free milk looks exactly like
// the milk it is made from. Rather than rename 26 files, the key points at
// the file it points at. If you ever redraw those, either name works --
// just update the right-hand side here.
//
// ---------------------------------------------------------------------
// Two constraints that have not changed
//
// 1. Metro needs require() paths to be STATIC string literals, which is why
//    this is an explicit map and not a loop over a template string.
//
// 2. Every entry here must have a matching file in Snack's assets folder.
//    A key listed with no uploaded file does NOT degrade gracefully --
//    Metro fails to resolve the require() and the build breaks. A key with
//    no ENTRY is fine: it falls back to the placeholder.
//
// 24 keys are still undrawn and deliberately absent below. See
// docs/icon-registry.md for which.
